-- TNT CMS runs through Next.js only. Do not add this schema to Supabase's exposed schemas.
CREATE SCHEMA IF NOT EXISTS tnt_cms;
REVOKE ALL ON SCHEMA tnt_cms FROM PUBLIC;

CREATE TABLE tnt_cms.users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username varchar(50) NOT NULL UNIQUE CHECK (username ~ '^[a-z0-9][a-z0-9._-]{2,49}$'),
  display_name varchar(120) NOT NULL,
  email varchar(254) NOT NULL,
  password_hash varchar(255) NOT NULL,
  role text NOT NULL CHECK (role IN ('admin', 'editor', 'viewer')),
  active boolean NOT NULL DEFAULT true,
  auth_version integer NOT NULL DEFAULT 1 CHECK (auth_version > 0),
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email ON tnt_cms.users (lower(email));
CREATE UNIQUE INDEX one_fixed_admin ON tnt_cms.users ((role)) WHERE role = 'admin';

CREATE FUNCTION tnt_cms.protect_admin() RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF OLD.role = 'admin' THEN
    IF TG_OP = 'DELETE' THEN
      RAISE EXCEPTION 'The fixed admin cannot be deleted' USING ERRCODE = '23514';
    END IF;
    IF NEW.role <> 'admin' OR NOT NEW.active OR NEW.username <> OLD.username THEN
      RAISE EXCEPTION 'The fixed admin identity and role are immutable' USING ERRCODE = '23514';
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER protect_admin BEFORE UPDATE OR DELETE ON tnt_cms.users
  FOR EACH ROW EXECUTE FUNCTION tnt_cms.protect_admin();

CREATE TABLE tnt_cms.leads (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(120) NOT NULL,
  email_or_phone varchar(254) NOT NULL,
  company varchar(160) NOT NULL,
  interest varchar(160) NOT NULL,
  industry varchar(160) NOT NULL DEFAULT '',
  company_size varchar(80) NOT NULL DEFAULT '',
  message text NOT NULL DEFAULT '',
  consent boolean NOT NULL CHECK (consent),
  context text NOT NULL CHECK (context IN ('general', 'food-processing', 'erp', 'outsourcing', 'body-shop')),
  source varchar(300) NOT NULL,
  details jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
  status text NOT NULL DEFAULT 'new' CHECK (status IN ('new', 'contacted', 'in_progress', 'closed', 'spam')),
  notes text NOT NULL DEFAULT '',
  submission_key text UNIQUE,
  payload_hash text,
  version integer NOT NULL DEFAULT 1 CHECK (version > 0),
  created_by integer REFERENCES tnt_cms.users(id) ON DELETE SET NULL,
  updated_by integer REFERENCES tnt_cms.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX leads_status_created ON tnt_cms.leads (status, created_at DESC, id DESC);
CREATE INDEX leads_context_created ON tnt_cms.leads (context, created_at DESC, id DESC);
CREATE INDEX leads_created ON tnt_cms.leads (created_at DESC, id DESC);

CREATE TABLE tnt_cms.sessions (
  token_hash text PRIMARY KEY,
  csrf_token text NOT NULL,
  user_id integer REFERENCES tnt_cms.users(id) ON DELETE CASCADE,
  auth_version integer,
  created_at timestamptz NOT NULL DEFAULT now(),
  last_seen timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT now() + interval '8 hours'
);
CREATE INDEX sessions_expires ON tnt_cms.sessions (expires_at);

CREATE TABLE tnt_cms.rate_limits (
  bucket text PRIMARY KEY,
  hits integer NOT NULL DEFAULT 1,
  expires_at timestamptz NOT NULL
);
CREATE INDEX rate_limits_expires ON tnt_cms.rate_limits (expires_at);

CREATE TABLE tnt_cms.audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor_id integer REFERENCES tnt_cms.users(id) ON DELETE SET NULL,
  action varchar(50) NOT NULL,
  entity_type varchar(30) NOT NULL,
  entity_id integer,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_created ON tnt_cms.audit_log (created_at);

CREATE TABLE tnt_cms.legacy_imports (
  source_hash text PRIMARY KEY,
  user_count integer NOT NULL,
  lead_count integer NOT NULL,
  imported_at timestamptz NOT NULL DEFAULT now()
);

-- No browser role can access passwords, sessions or lead data through the Data API.
ALTER TABLE tnt_cms.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE tnt_cms.leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE tnt_cms.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE tnt_cms.rate_limits ENABLE ROW LEVEL SECURITY;
ALTER TABLE tnt_cms.audit_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE tnt_cms.legacy_imports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA tnt_cms FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA tnt_cms FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA tnt_cms FROM PUBLIC;
DO $$
DECLARE web_role text;
BEGIN
  FOREACH web_role IN ARRAY ARRAY['anon', 'authenticated', 'service_role'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = web_role) THEN
      EXECUTE format('REVOKE ALL ON SCHEMA tnt_cms FROM %I', web_role);
      EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA tnt_cms FROM %I', web_role);
      EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA tnt_cms FROM %I', web_role);
      EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA tnt_cms FROM %I', web_role);
    END IF;
  END LOOP;
END;
$$;
